import crypto from "node:crypto";
import bcrypt from "bcryptjs";
import type { Role } from "@prisma/client";
import { prisma } from "@/lib/db";
import { AppError } from "@/lib/errors";

/**
 * Account provisioning (public self-registration is disabled):
 *  - ADMIN creates accounts of any role.
 *  - TEACHER creates STUDENT accounts (enrolled into one of their classes) and
 *    PARENT accounts (linked to a student of one of their classes).
 */
export interface CreateAccountInput {
  name: string;
  email: string;
  role: Role;
  password?: string;
  phone?: string;
  /** required for teachers: the class the student joins / the parent's child belongs to */
  classId?: string;
  /** required when a teacher creates a PARENT: the child (must be ACTIVE in classId) */
  studentId?: string;
  relation?: string;
}

export interface CreateAccountResult {
  user: { id: string; name: string; email: string; role: Role };
  /** only when the password was generated by the system: shown ONCE to the creator */
  temporaryPassword: string | null;
  /** a teacher creating a parent whose email already exists as a PARENT just gets linked */
  linkedExistingParent: boolean;
}

const PASSWORD_ALPHABET = "abcdefghjkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789";

export function generateTemporaryPassword(length = 10): string {
  const bytes = crypto.randomBytes(length);
  let out = "";
  for (let i = 0; i < length; i++) out += PASSWORD_ALPHABET[bytes[i]! % PASSWORD_ALPHABET.length];
  return out;
}

async function assertTeacherOwnsClass(teacherId: string, classId: string | undefined) {
  if (!classId) {
    throw new AppError("Vui lòng chọn lớp học.", 400, "CLASS_REQUIRED");
  }
  const cls = await prisma.class.findUnique({ where: { id: classId }, select: { id: true, teacherId: true } });
  if (!cls) throw new AppError("Không tìm thấy lớp học.", 404, "NOT_FOUND");
  if (cls.teacherId !== teacherId) {
    throw new AppError("Bạn không có quyền quản lý lớp học này.", 403, "FORBIDDEN");
  }
  return cls;
}

export async function createAccount(
  actor: { id: string; role: Role },
  input: CreateAccountInput
): Promise<CreateAccountResult> {
  const email = input.email.trim().toLowerCase();
  const name = input.name.trim();

  if (actor.role !== "ADMIN" && actor.role !== "TEACHER") {
    throw new AppError("Bạn không có quyền tạo tài khoản.", 403, "FORBIDDEN");
  }
  if (actor.role === "TEACHER" && input.role !== "STUDENT" && input.role !== "PARENT") {
    throw new AppError("Giáo viên chỉ được tạo tài khoản Học sinh hoặc Phụ huynh.", 403, "FORBIDDEN");
  }

  // Teacher scope checks (done before touching the users table)
  let childId: string | null = null;
  if (actor.role === "TEACHER") {
    const cls = await assertTeacherOwnsClass(actor.id, input.classId);
    if (input.role === "PARENT") {
      if (!input.studentId) {
        throw new AppError("Vui lòng chọn học sinh để liên kết với phụ huynh.", 400, "STUDENT_REQUIRED");
      }
      const enr = await prisma.enrollment.findUnique({
        where: { classId_studentId: { classId: cls.id, studentId: input.studentId } },
        select: { status: true },
      });
      if (!enr || enr.status !== "ACTIVE") {
        throw new AppError("Học sinh không thuộc lớp này.", 403, "FORBIDDEN");
      }
      childId = input.studentId;
    }
  } else if (input.role === "PARENT" && input.studentId) {
    const child = await prisma.user.findUnique({ where: { id: input.studentId }, select: { role: true } });
    if (!child || child.role !== "STUDENT") {
      throw new AppError("Không tìm thấy học sinh để liên kết.", 404, "NOT_FOUND");
    }
    childId = input.studentId;
  }

  const existing = await prisma.user.findUnique({
    where: { email },
    select: { id: true, name: true, email: true, role: true },
  });

  // Existing parent account: just link it to the child instead of failing
  if (existing && input.role === "PARENT" && existing.role === "PARENT" && childId) {
    const now = new Date();
    await prisma.parentLink.upsert({
      where: { parentId_studentId: { parentId: existing.id, studentId: childId } },
      create: { parentId: existing.id, studentId: childId, relation: input.relation ?? "Phụ huynh", verifiedAt: now },
      update: { verifiedAt: now, ...(input.relation ? { relation: input.relation } : {}) },
    });
    return { user: existing, temporaryPassword: null, linkedExistingParent: true };
  }
  if (existing) {
    throw new AppError("Email này đã được đăng ký.", 409, "EMAIL_EXISTS");
  }
  if (input.phone) {
    const phoneUsed = await prisma.user.findUnique({ where: { phone: input.phone }, select: { id: true } });
    if (phoneUsed) throw new AppError("Số điện thoại này đã được đăng ký.", 409, "PHONE_EXISTS");
  }

  const temporaryPassword = input.password ? null : generateTemporaryPassword();
  const passwordHash = await bcrypt.hash(input.password ?? temporaryPassword!, 10);

  const user = await prisma.$transaction(async (tx) => {
    const created = await tx.user.create({
      data: { name, email, phone: input.phone ?? null, passwordHash, role: input.role },
      select: { id: true, name: true, email: true, role: true },
    });
    if (actor.role === "TEACHER" && input.role === "STUDENT") {
      await tx.enrollment.create({
        data: { classId: input.classId!, studentId: created.id, status: "ACTIVE" },
      });
    } else if (actor.role === "ADMIN" && input.role === "STUDENT" && input.classId) {
      await tx.enrollment.create({
        data: { classId: input.classId, studentId: created.id, status: "ACTIVE" },
      });
    }
    if (input.role === "PARENT" && childId) {
      await tx.parentLink.create({
        data: {
          parentId: created.id,
          studentId: childId,
          relation: input.relation ?? "Phụ huynh",
          verifiedAt: new Date(),
        },
      });
    }
    return created;
  });

  return { user, temporaryPassword, linkedExistingParent: false };
}
